/**
 * 04c-ai-code-detector.ts — Stage 4c: AI-generated code detection.
 *
 * Scans source files for known AI code markers (deterministic) and then
 * asks Claude to flag suspicious files (semantic). Result is stored in
 * ctx.aiUsageAnalysis — it does NOT affect scoring, only generates a warning.
 *
 * Warning is surfaced in the student dashboard under the evaluation results.
 */

import { callLlmWithFallback } from '../llm/llm-provider.js';
import { logger } from '../logger.js';
import type { PipelineContext, AiUsageAnalysis } from '../pipeline-context.js';

// Known AI-generated code markers (case-insensitive patterns)
const AI_MARKERS = [
  /generated by (chatgpt|gpt|claude|copilot|ai|openai|anthropic|gemini|bard)/i,
  /ai[- ]?generated/i,
  /copilot[- ]?generated/i,
  /this code was (written|generated|created) by/i,
  /# (chatgpt|claude|copilot|gpt-4|gpt-3)/i,
  /\/\/ (chatgpt|claude|copilot|gpt-4|gpt-3)/i,
  /\* (chatgpt|claude|copilot|gpt)/i,
];

export async function detectAiCode(ctx: PipelineContext): Promise<void> {
  const { evaluationId, fileContentsMap } = ctx;

  const fileEntries = Object.entries(fileContentsMap);
  if (fileEntries.length === 0) {
    ctx.aiUsageAnalysis = {
      policy: 'AI assistance is allowed but must be disclosed.',
      status: 'no_explicit_markers',
      warning: null,
      markers: [],
      suspectedFiles: [],
    };
    return;
  }

  logger.info('Detecting AI-generated code', { evaluationId, stage: 'aiDetector', fileCount: fileEntries.length });

  // ── Step 1: Deterministic marker scan ──────────────────────────────────────
  const markerHits: string[] = [];
  const suspectedByMarker: string[] = [];

  for (const [filePath, content] of fileEntries) {
    for (const pattern of AI_MARKERS) {
      if (pattern.test(content)) {
        markerHits.push(`${filePath}: matched "${pattern.source}"`);
        if (!suspectedByMarker.includes(filePath)) {
          suspectedByMarker.push(filePath);
        }
        break;
      }
    }
  }

  // ── Step 2: LLM semantic check on a sample of files ────────────────────────
  // Only check up to 10 files to keep this fast (< 30 seconds)
  const sampleFiles = fileEntries.slice(0, 10);
  let suspectedByClaude: string[] = [];

  try {
    const fileSnippets = sampleFiles
      .map(([path, content]) => {
        const preview = content.slice(0, 800);
        return `FILE: ${path}\n\`\`\`\n${preview}\n\`\`\``;
      })
      .join('\n\n');

    const prompt = `You are reviewing code files from a student's project submission.

Your task: identify which files (if any) appear to be AI-generated rather than written by the student.

Signs of AI-generated code:
- Unusually perfect, comprehensive docstrings on every function
- Boilerplate that exactly matches common tutorial outputs
- Generic variable names (data, result, response) with no domain context
- Code that's "too perfect" — handles all edge cases without errors or TODOs
- Entire files that look like they came straight from documentation examples

Files to review:
${fileSnippets}

Respond with JSON only:
{
  "suspectedAiFiles": ["path/to/file.py"],
  "reasoning": "brief explanation"
}

If no files appear AI-generated, return: {"suspectedAiFiles": [], "reasoning": "no AI patterns detected"}`;

    const res = await callLlmWithFallback({
      taskName: 'ai-code-detector',
      taskType: 'analysis',
      systemPrompt: 'You are a code reviewer identifying AI-generated code. Output only valid JSON.',
      userPrompt: prompt,
      temperature: 0.1,
      maxTokens: 512,
      responseFormat: 'json_object',
    });

    const jsonMatch = res.rawText.match(/\{[\s\S]*\}/);
    if (jsonMatch) {
      const parsed = JSON.parse(jsonMatch[0]) as { suspectedAiFiles: string[]; reasoning: string };
      suspectedByClaude = parsed.suspectedAiFiles ?? [];
    }
  } catch (err) {
    logger.warn('AI code detector LLM call failed (non-fatal)', { evaluationId, error: String(err) });
  }

  // ── Combine results ─────────────────────────────────────────────────────────
  const allSuspected = [...new Set([...suspectedByMarker, ...suspectedByClaude])];
  const hasMarkers = markerHits.length > 0;
  const hasSuspected = allSuspected.length > 0;

  let status: AiUsageAnalysis['status'];
  let warning: string | null = null;

  if (hasMarkers) {
    status = 'disclosed_or_marked';
    warning = `AI-assistance markers were found in ${suspectedByMarker.length} file(s): ${suspectedByMarker.join(', ')}. AI-assisted code was not counted toward your score. Review these files and ensure you understand the implementation.`;
  } else if (hasSuspected) {
    status = 'suspected_ai_code';
    warning = `${allSuspected.length} file(s) appear potentially AI-generated: ${allSuspected.join(', ')}. AI-assisted code is not counted toward your score. Please ensure you can explain your implementation and design decisions.`;
  } else {
    status = 'no_explicit_markers';
    warning = null;
  }

  ctx.aiUsageAnalysis = {
    policy: 'AI assistance is allowed but must be disclosed. AI-generated code does not reduce your score but will be flagged.',
    status,
    warning,
    markers: markerHits,
    suspectedFiles: allSuspected,
  };

  logger.info('AI code detection complete', {
    evaluationId,
    stage: 'aiDetector',
    status,
    markerHits: markerHits.length,
    suspectedFiles: allSuspected.length,
  });
}
