// ── Emoji stripper — used everywhere AI text is rendered ─────────────────────
export function stripEmojis(text: string): string {
  return text
    .replace(
      /[\u{1F000}-\u{1FFFF}]|[\u{2600}-\u{26FF}]|[\u{2700}-\u{27BF}]|[\u{FE00}-\u{FE0F}]|[\u{1F900}-\u{1F9FF}]|[\u{1FA00}-\u{1FA6F}]|[\u{1FA70}-\u{1FAFF}]/gu,
      ''
    )
    .replace(/\s{2,}/g, ' ')
    .trim();
}

