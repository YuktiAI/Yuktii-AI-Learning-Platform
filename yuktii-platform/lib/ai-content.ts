// Fallback for any domain slug not in the map above
const DEFAULT_STAGE_TITLES = [
  'Environment Setup & Core Fundamentals',
  'Data Pipeline & Initial Implementation',
  'Core Logic & Feature Integration',
  'Validation, Testing & Error Handling',
  'Performance Optimization & Benchmarking',
  'Integration & API Deployment',
  'Security, Logging & Monitoring',
  'Capstone Presentation & Production Release',
];

function getStageTitleForDomain(domainSlug: string, stageNumber: number): string {
  const titles = DOMAIN_STAGE_TITLES[domainSlug] ?? DEFAULT_STAGE_TITLES;
  return titles[stageNumber - 1] ?? `Stage ${stageNumber}`;
}

export async function generateStaticStageContent(
  domainName: string,
  levelName: string,
  stageNumber: number,
  totalStages: number,
  domainSlug?: string,
): Promise<StaticStageContent> {
  const slug = domainSlug ?? domainName.toLowerCase().replace(/[\s/&()]+/g, '-');
  const title = getStageTitleForDomain(slug, stageNumber);

  const isWarmUp = stageNumber === 1;
  const isCapstone = stageNumber === totalStages && totalStages > 1;

  const roleLabel = isWarmUp ? 'warm-up' : isCapstone ? 'industry project capstone' : 'applied';

  return {
    title,
    plainLanguageIntro:
      `Welcome to Stage ${stageNumber}${isWarmUp ? ' (Warm-Up)' : isCapstone ? ' (Industry Project)' : ''} of your ${domainName} ${levelName} track. ` +
      (isWarmUp
        ? 'This first stage is designed to get you comfortable with the tools and project you will be working on throughout the track. Your personalised project scenario will appear here — take time to understand it before you begin. '
        : isCapstone
        ? 'This final stage is your industry project — a full, realistic, production-flavored version of your assigned scenario. Treat this as you would a deliverable for a real employer. '
        : 'In this stage you will apply real techniques to your ongoing project scenario. Read the task brief carefully and reference what you built in previous stages. ') +
      'Your AI-personalised task will appear below when this stage is unlocked.',
    learningObjectives:
      `Apply core ${domainName} techniques to a structured real-world problem\n` +
      'Produce clean, documented, working deliverables\n' +
      `Demonstrate ${levelName}-appropriate technical depth\n` +
      `Validate your solution against the provided acceptance criteria\n` +
      (isCapstone ? 'Deliver a production-quality, professionally documented project suitable for portfolio inclusion' : ''),
    taskTemplate:
      `TASK — Stage ${stageNumber}: ${title} [${roleLabel.toUpperCase()}]\n\n` +
      'Your personalised project scenario will appear here when you open this stage.\n\n' +
      'Deliverables (all required):\n' +
      '1. Public GitHub repository or Google Colab notebook\n' +
      '2. README explaining what you built and how to run it\n' +
      '3. Working evidence: screenshots, test output, or live URL\n' +
      '4. Short reflection (3-5 sentences)\n\n' +
      'Submit a public URL. The AI evaluator will check your link.',
    modelAnswer:
      `A strong Stage ${stageNumber} (${roleLabel}) submission demonstrates:\n\n` +
      `1. Correct implementation of the core ${title} requirement\n` +
      '2. Clean, readable code with meaningful comments\n' +
      '3. Working evidence the solution functions as specified\n' +
      '4. A README enabling someone to run the project in under 5 minutes\n' +
      (isCapstone
        ? '5. Production-quality polish: error handling, edge cases, documented tradeoffs\n6. Professional reflection on real-world constraints and design decisions'
        : '5. Genuine understanding of tradeoffs made'),
    rubricJson: JSON.stringify([
      'Submission URL is publicly accessible and contains real, non-trivial work',
      `Core ${title} requirement is correctly implemented`,
      'Code is clean and readable with meaningful comments',
      'README clearly explains the approach and how to reproduce results',
      isCapstone
        ? 'Solution meets production-quality standards: error handling, edge cases, and documented tradeoffs'
        : 'Reflection demonstrates genuine understanding of the implementation',
    ]),
  };
}

